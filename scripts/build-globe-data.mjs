// Builds the globe data for components/ui/globe.tsx and the hero's InteractiveGlobe.
//
// Source: Natural Earth 1:110m land (public domain), via the world-atlas@2.0.2
// package's land-110m.json (ISC). The download is not committed; only the output is.
//
// Usage: node scripts/build-globe-data.mjs <path/to/land-110m.json>
//
// Writes two files:
// - components/ui/globe-utils/svg-globe-path.ts: the land dots of the top of a globe
//   (a dome), seen from the front in a 1259x477 frame, plus its limb arc (the 404).
// - components/ui/globe-utils/globe-land-shapes.ts: the land as a GeoJSON
//   MultiPolygon, for the rotating hero globe to project and fill.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const input = process.argv[2];
if (!input) {
  console.error("Usage: node scripts/build-globe-data.mjs <path/to/land-110m.json>");
  process.exit(1);
}
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const topo = JSON.parse(readFileSync(input, "utf8"));

const DEG = Math.PI / 180;
/** The dome spans the full frame width at its base; the sphere's centre sits below the frame. */
const FRAME = { width: 1259, height: 477, cx: 629.5, cy: 668, r: 658 };
/** Atlantic-centred: the Americas on the left, Europe and Africa on the right. */
const VIEW = { tilt: 0, phi: 20 * DEG };
/** Dot grid: 2.4 degree rows, 150 dots around the equator. */
const ROWS = 75;
const COLS = 150;

// 1. Decode the TopoJSON arcs (quantised, delta-encoded) into lon/lat polygons.
const [sx, sy] = topo.transform.scale;
const [tx, ty] = topo.transform.translate;
const arcs = topo.arcs.map((arc) => {
  let x = 0;
  let y = 0;
  return arc.map(([dx, dy]) => {
    x += dx;
    y += dy;
    return [x * sx + tx, y * sy + ty];
  });
});
const ringFrom = (indices) =>
  indices.flatMap((index, k) => {
    const arc = index < 0 ? [...arcs[~index]].reverse() : arcs[index];
    return k === 0 ? arc : arc.slice(1);
  });
const polygons = topo.objects.land.geometries.flatMap((geometry) =>
  (geometry.type === "Polygon" ? [geometry.arcs] : geometry.arcs).map((polygon) =>
    polygon.map(ringFrom),
  ),
);
const rings = polygons.flat();

// 2. Rasterise to an equirectangular land mask (row 0 = north) with an even-odd fill.
const W = 512;
const H = 256;
const mask = new Uint8Array(W * H);
for (let row = 0; row < H; row++) {
  const lat = 90 - ((row + 0.5) * 180) / H;
  const xs = [];
  for (const ring of rings) {
    for (let i = 0; i < ring.length - 1; i++) {
      const [x1, y1] = ring[i];
      const [x2, y2] = ring[i + 1];
      if ((y1 <= lat && y2 > lat) || (y2 <= lat && y1 > lat)) {
        xs.push(x1 + ((lat - y1) / (y2 - y1)) * (x2 - x1));
      }
    }
  }
  xs.sort((a, b) => a - b);
  for (let k = 0; k + 1 < xs.length; k += 2) {
    const c0 = Math.max(0, Math.ceil(((xs[k] + 180) / 360) * W - 0.5));
    const c1 = Math.min(W - 1, Math.floor(((xs[k + 1] + 180) / 360) * W - 0.5));
    for (let c = c0; c <= c1; c++) mask[row * W + c] = 1;
  }
}
const isLand = (lat, lon) => {
  const row = Math.min(H - 1, Math.max(0, Math.floor(((90 - lat) / 180) * H)));
  const col = ((Math.floor(((lon + 180) / 360) * W) % W) + W) % W;
  return mask[row * W + col] === 1;
};

// 3. Orthographic projection onto the frame.
function project(latDeg, lonDeg) {
  const lat = latDeg * DEG;
  const lon = lonDeg * DEG + VIEW.phi;
  const x = Math.cos(lat) * Math.sin(lon);
  const y = Math.sin(lat);
  const z = Math.cos(lat) * Math.cos(lon);
  const ct = Math.cos(VIEW.tilt);
  const st = Math.sin(VIEW.tilt);
  return {
    x: FRAME.cx + FRAME.r * x,
    y: FRAME.cy - FRAME.r * (y * ct - z * st),
    z: y * st + z * ct,
  };
}
const inFrame = (p) =>
  p.z > 0.04 && p.x >= 4 && p.x <= FRAME.width - 4 && p.y >= 4 && p.y <= FRAME.height - 4;

let dots = "";
let count = 0;
for (let i = 0; i < ROWS; i++) {
  const lat = -90 + ((i + 0.5) * 180) / ROWS;
  const n = Math.max(1, Math.round(COLS * Math.cos(lat * DEG)));
  for (let j = 0; j < n; j++) {
    const lon = -180 + ((j + 0.5) * 360) / n;
    if (!isLand(lat, lon)) continue;
    const p = project(lat, lon);
    if (!inFrame(p)) continue;
    dots += `M${Math.round(p.x)} ${Math.round(p.y)}h0`;
    count++;
  }
}

const half = Math.sqrt(FRAME.r ** 2 - (FRAME.cy - FRAME.height) ** 2);
const limb = `M${Math.round(FRAME.cx - half)} ${FRAME.height}A${FRAME.r} ${FRAME.r} 0 0 1 ${Math.round(FRAME.cx + half)} ${FRAME.height}`;

writeFileSync(
  join(root, "components/ui/globe-utils/svg-globe-path.ts"),
  "// Generated by scripts/build-globe-data.mjs from Natural Earth 1:110m land\n" +
    "// (public domain, via world-atlas@2.0.2). Do not edit by hand.\n\n" +
    "/** Land dots (as round-capped zero-length strokes) and the limb arc, in a 1259x477 frame. */\n" +
    "export const SVG_GLOBE_PATH = {\n" +
    `  dots: "${dots}",\n` +
    `  limb: "${limb}",\n` +
    "} as const;\n",
);

// 4. The hero globe's land: the same polygons, rounded to 0.01 degrees.
const shapes = polygons.map((polygon) =>
  polygon.map((ring) => ring.map(([x, y]) => [Math.round(x * 100) / 100, Math.round(y * 100) / 100])),
);

writeFileSync(
  join(root, "components/ui/globe-utils/globe-land-shapes.ts"),
  "// Generated by scripts/build-globe-data.mjs from Natural Earth 1:110m land\n" +
    "// (public domain, via world-atlas@2.0.2). Do not edit by hand.\n\n" +
    'import type { GeoGeometryObjects } from "d3-geo";\n\n' +
    "/** Land as [longitude, latitude] rings, wound the way d3-geo expects. */\n" +
    `export const LAND_SHAPES: GeoGeometryObjects = { type: "MultiPolygon", coordinates: ${JSON.stringify(shapes)} };\n`,
);

console.log(`rings ${rings.length}, dots ${count}, path ${dots.length} chars, land ${polygons.length} polygons`);
